import { test, expect } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";
const fixture = JSON.parse(fs.readFileSync(process.env.AEL_FINDINGS_FIXTURE!, "utf8"));
test("发现归并、来源、证据与受检版本可追溯", async ({ page }) => {
  await page.goto(fixture.url + "/#/tasks/scan?project=shared&section=findings");
  await page.getByLabel("用户名", { exact: true }).fill("observer");
  await page.getByLabel("密码", { exact: true }).fill("fixture-observer-password");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  const panel = page.getByRole("region", { name: "结构化发现" });
  await expect(panel.getByRole("button", { name: "Clipped action label", exact: true })).toHaveCount(3);
  await page.getByLabel("搜索发现").fill("unmatched isolated query");
  await page.getByLabel("搜索发现").press("Tab");
  await expect(panel).toContainText("当前筛选没有匹配的发现。");
  await panel.getByRole("button", { name: "清除筛选" }).click();
  await expect(panel.getByRole("button", { name: "Clipped action label", exact: true })).toHaveCount(3);
  await page.goto(fixture.url + "/#/tasks/scan?project=shared&section=checks&check=flow");
  await expect(panel).toContainText("检查 flow");
  await expect(panel.getByRole("button", { name: "Clipped action label", exact: true })).toHaveCount(0);
  await panel.getByRole("button", { name: "全部发现", exact: true }).click();
  await expect(panel.getByRole("button", { name: "Clipped action label", exact: true })).toHaveCount(3);
  await page.getByLabel("证据完整性", { exact: true }).selectOption("incomplete");
  await expect(panel.getByRole("button", { name: "Clipped action label", exact: true })).toHaveCount(1);
  await panel.getByRole("button", { name: "Clipped action label", exact: true }).click();
  await expect(panel).toContainText("待补证 · 原始报告");
  await panel.getByRole("button", { name: "返回发现列表", exact: true }).click();
  await page.getByLabel("证据完整性", { exact: true }).selectOption("");
  await page.goto(fixture.url + "/#/tasks/scan?project=shared&section=findings&finding=" + fixture.finding);
  await expect(panel).toContainText("出现 2 次");
  await expect(panel).toContainText("模型建议 · client-a");
  await expect(panel).toContainText(fixture.candidate);
  await expect(panel).toContainText("#save");
  await panel.getByRole("button", { name: "查看原始报告", exact: true }).first().click();
  await expect(page.locator(".artifact-panel")).toContainText("deterministic source classification");
  await page.getByRole("button", { name: "关闭证据", exact: true }).click();
  await panel.getByRole("button", { name: "查看截图", exact: true }).first().click();
  await expect(page.locator(".artifact-panel img")).toBeVisible();
  await expect.poll(() => page.locator(".artifact-panel img").evaluate((element: HTMLImageElement) => element.naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: path.join(fixture.out, "finding-detail.png"), fullPage: true });
  await page.getByRole("button", { name: "关闭证据", exact: true }).click();
  await page.goto(fixture.url + "/#/tasks/empty-findings?project=shared&section=findings");
  await expect(panel).toContainText("本任务暂无发现。");
  await expect(panel.getByLabel("证据完整性")).toHaveCount(0);
  await expect(panel.getByRole("navigation", { name: "发现分页" })).toHaveCount(0);
  const other = await page.request.get(fixture.url + "/api/v1/projects/other/findings/" + fixture.finding);
  expect(other.status()).toBe(404);
  const session = await (await page.request.get(fixture.url + "/api/v1/auth/session")).json();
  const denied = await page.request.post(fixture.url + "/api/v1/projects/shared/findings", { headers: { Origin: fixture.url, "X-AEL-CSRF": session.csrf, "X-AEL-Protocol": "1" }, data: {} });
  expect(denied.status()).toBe(403);
});
